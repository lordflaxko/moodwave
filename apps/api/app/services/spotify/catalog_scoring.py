def catalog_id(row: CatalogRow) -> str:
    return "demo_" + hashlib.md5(f"{row.title}|{row.artist}".encode()).hexdigest()[:14]


_DATA = Path(__file__).resolve().parents[2] / "data"


@cache
def artwork_map() -> dict[str, str]:
    """catalog id -> album cover URL (generated by scripts/fetch_artwork.py)."""
    path = _DATA / "artwork.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


@cache
def artist_image_map() -> dict[str, str]:
    """artist name -> portrait URL (generated by scripts/fetch_artwork.py)."""
    path = _DATA / "artist_images.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def _thumb(url: str | None) -> str | None:
    """Deezer/Apple artwork at ~500px instead of the 1000px original."""
    if not url:
        return url
    return url.replace("/1000x1000-", "/500x500-").replace("/1000x1000bb.", "/500x500bb.")


def row_to_track(row: CatalogRow, reason: str | None = None) -> Track:
    tid = catalog_id(row)
    art = artwork_map().get(tid)
    return Track(
        id=tid,
        uri=f"demo:track:{tid}",
        title=row.title,
        artists=[row.artist],
        artist_images=[artist_image_map().get(row.artist)],
        album=row.album,
        image_url=_thumb(art),
        image_large=art,
        duration_ms=row.seconds * 1000,
        explicit=row.explicit,
        popularity=row.popularity,
        external_url=None,
        release_year=row.year,
        energy=row.energy,
        reason=reason,
    )


CATALOG_BY_ID: dict[str, CatalogRow] = {catalog_id(row): row for row in CATALOG}


def expand_genres(genres: list[str]) -> set[str]:
    expanded: set[str] = set()
    for genre in genres:
        key = genre.lower().strip()
        expanded.add(key)
        expanded |= GENRE_FAMILIES.get(key, set())
        # Partial matches: "mellow indie" -> indie family
        for family, members in GENRE_FAMILIES.items():
            if family in key:
                expanded |= members
    return expanded


def _era_matches(era: str | None, year: int) -> bool:
    if not era:
        return False
    era = era.lower()
    for decade in ("60", "70", "80", "90", "00", "10", "20"):
        if f"{decade}s" in era:
            start = int(("19" if decade in ("60", "70", "80", "90") else "20") + decade)
            return start <= year < start + 10
    if "classic" in era or "retro" in era or "vintage" in era:
        return year < 2000
    if "modern" in era or "recent" in era or "new" in era:
        return year >= 2015
    return False


DEEP_CUTS_TRAIT = "deep cuts over hits"


def score_row(row: CatalogRow, intent: MusicalIntent) -> float:
    # The first genre is usually what the listener asked for explicitly; weight it highest.
    primary = expand_genres(intent.genres[:1])
    secondary = expand_genres(intent.genres[1:])
    score = 1.0
    score -= abs(row.energy - intent.energy) * 1.6
    score -= abs(row.valence - intent.valence) * 0.7
    if row.genre in primary:
        score += 0.95
    elif row.genre in secondary:
        score += 0.5
    if intent.tempo_min <= row.bpm <= intent.tempo_max:
        score += 0.15
    if intent.vocals != "any":
        if row.vocals == intent.vocals or (intent.vocals in ("female", "male") and row.vocals == "mixed"):
            score += 0.35
        else:
            score -= 0.45
    if any(a.lower() == row.artist.lower() for a in intent.reference_artists):
        score += 0.4
    if _era_matches(intent.era, row.year):
        score += 0.25
    if DEEP_CUTS_TRAIT in intent.characteristics:
        score -= max(0, row.popularity - 68) / 30
    else:
        score += row.popularity / 1000  # gentle tie-breaker
    return score


def rank_catalog(
    intent: MusicalIntent, exclude_ids: set[str] | None = None, artists: set[str] | None = None
) -> list[CatalogRow]:
    """Rank catalog rows for an intent; `artists` optionally restricts to a line-up."""
    exclude_ids = exclude_ids or set()
    rows = [
        row
        for row in CATALOG
        if catalog_id(row) not in exclude_ids
        and (intent.explicit_allowed or not row.explicit)
        and (artists is None or row.artist in artists)
    ]
    return sorted(rows, key=lambda row: score_row(row, intent), reverse=True)
